"""Purpose-scoped data access (SPEC 17.2): compiles policy/access.yaml into policy/compiled/policy.json and the BigQuery
grant plan infra/gcp/grants.json, and refuses a policy that breaks the shared-project rules. Pattern from PeopleVault
pipelines/src/peoplevault/policy/compile.py (MIT).

Rules: every dataset, service account and job label starts with the prefix; every data grant is dataset-scoped; the
only project-level role is BigQuery Job User; the Worker reads exactly the published, semantic and lab datasets plus
authorized views in the audit dataset; every job carries a bytes cap and the app label. The project ID is never
written: members carry the <PROJECT_ID> placeholder that setup fills from .prod/state.json.
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[4]
SOURCE = ROOT / "policy" / "access.yaml"
COMPILED = ROOT / "policy" / "compiled" / "policy.json"
GRANTS = ROOT / "infra" / "gcp" / "grants.json"
WORKER = "staysignal-worker"
WORKER_READS = {"staysignal_published", "staysignal_semantic", "staysignal_lab"}
JOB_USER = "roles/bigquery.jobUser"
VIEWER = "roles/bigquery.dataViewer"
EDITOR = "roles/bigquery.dataEditor"


class PolicyError(ValueError):
    pass


def member(identity: str) -> str:
    return f"serviceAccount:{identity}@<PROJECT_ID>.iam.gserviceaccount.com"


def compile_policy(src: dict) -> tuple[dict, dict]:
    prefix = src["naming"]["prefix"]
    datasets: dict[str, str] = src["datasets"]
    purposes: dict[str, dict] = src["purposes"]
    identities: dict[str, dict] = src["identities"]
    problems = [f"dataset {d} lacks the prefix {prefix}_" for d in datasets if not d.startswith(f"{prefix}_")]
    problems += [f"identity {i} lacks the prefix {prefix}-" for i in identities if not i.startswith(f"{prefix}-")]
    problems += [f"job label {k}={v} must name the app" for k, v in src["job_labels"].items() if v != prefix]
    for name, p in purposes.items():
        for d in [*p.get("reads", []), *p.get("writes", [])]:
            if d not in datasets:
                problems.append(f"purpose {name} names an unknown dataset {d}")
    grants: dict[tuple[str, str], str] = {}

    def grant(dataset: str, identity: str, role: str) -> None:
        if dataset not in datasets:
            problems.append(f"{identity} is granted an unknown dataset {dataset}")
            return
        if grants.get((dataset, identity)) == EDITOR:
            return
        grants[(dataset, identity)] = role

    views = []
    for ident, spec in identities.items():
        if "max_bytes_billed" not in spec:
            problems.append(f"{ident} has no max_bytes_billed")
        for d in spec.get("reads", []):
            grant(d, ident, VIEWER)
        for d in spec.get("loads", []):
            grant(d, ident, EDITOR)
        for pname in spec.get("purposes", []):
            p = purposes[pname]
            for d in p.get("reads", []):
                grant(d, ident, VIEWER)
            for d in p.get("writes", []):
                grant(d, ident, EDITOR)
        for v in spec.get("authorized_views", []):
            ds, _, view = v.partition(".")
            if ds not in datasets or not view:
                problems.append(f"{ident}'s authorized view {v} is not dataset.view in a known dataset")
            views.append({"dataset": ds, "view": view, "reader": member(ident)})
    worker_reads = {d for (d, i), _ in grants.items() if i == WORKER}
    if worker_reads != WORKER_READS:
        problems.append(f"the Worker must read exactly {sorted(WORKER_READS)}, not {sorted(worker_reads)}")
    if any(i == WORKER and r != VIEWER for (_, i), r in grants.items()):
        problems.append("the Worker never writes a dataset")
    if problems:
        raise PolicyError("; ".join(problems))
    plan = {
        "note": "generated by `npm run policy:compile` from policy/access.yaml; <PROJECT_ID> is filled by setup:prod",
        "location": src["location"],
        "datasets": [{"dataset": d, "description": desc} for d, desc in sorted(datasets.items())],
        "service_accounts": [
            {"account": i, "description": spec.get("description", "")} for i, spec in sorted(identities.items())
        ],
        "dataset_grants": [
            {"dataset": d, "member": member(i), "role": r} for (d, i), r in sorted(grants.items(), key=lambda x: x[0])
        ],
        "project_roles": [{"member": member(i), "role": JOB_USER} for i in sorted(identities)],
        "authorized_views": views,
        "jobs": {
            i: {"maximum_bytes_billed": spec["max_bytes_billed"], "labels": src["job_labels"]}
            for i, spec in sorted(identities.items())
        },
    }
    compiled = {
        "version": src["version"],
        "prefix": prefix,
        "purposes": purposes,
        "identities": {i: {k: v for k, v in spec.items() if k != "description"} for i, spec in identities.items()},
        "job_labels": src["job_labels"],
    }
    return compiled, plan


def dumps(doc: dict) -> str:
    return json.dumps(doc, indent=1, sort_keys=False) + "\n"


def build(check: bool = False) -> list[str]:
    """Writes the compiled policy and the grant plan; with `check`, returns the files that drifted instead."""
    compiled, plan = compile_policy(yaml.safe_load(SOURCE.read_text()))
    stale = []
    for path, doc in ((COMPILED, compiled), (GRANTS, plan)):
        text = dumps(doc)
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return stale


__all__ = ["GRANTS", "JOB_USER", "PolicyError", "build", "compile_policy", "member"]
