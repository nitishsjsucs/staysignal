// npm run fixtures:index: writes src/worker/generated/fixtures-index.ts, which imports every committed API fixture
// (test/fixtures/api/**.json) so the fixtures warehouse client and the fixture runner bundle them. `--check` fails
// when the committed index is stale.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = process.cwd();
const API = join(ROOT, "test", "fixtures", "api");
const JOBS = join(ROOT, "test", "fixtures", "jobs");
const RECORDINGS = join(ROOT, "demo", "recordings");
const OUT = join(ROOT, "src", "worker", "generated", "fixtures-index.ts");
const OUT_REC = join(ROOT, "src", "worker", "generated", "recordings-index.ts");

function walk(dir: string): string[] {
  const out: string[] = [];
  let names: string[] = [];
  try {
    names = readdirSync(dir).sort();
  } catch {
    return out;
  }
  for (const name of names) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (name.endsWith(".json")) out.push(full);
  }
  return out;
}

export function render(): string {
  const files = [...walk(API).map((f) => ({ f, key: relative(API, f) })), ...walk(JOBS).map((f) => ({ f, key: `jobs/${relative(JOBS, f)}` }))];
  const lines = ["// Generated by scripts/gen-fixtures.ts from test/fixtures/api and test/fixtures/jobs; do not edit.", ""];
  files.forEach(({ f }, i) => lines.push(`import f${i} from "${relative(join(ROOT, "src", "worker", "generated"), f)}";`));
  lines.push("", "export const FIXTURES: Record<string, unknown> = {");
  files.forEach(({ key }, i) => lines.push(`  "${key}": f${i},`));
  lines.push("};", "");
  return lines.join("\n");
}

export function renderRecordings(): string {
  const files = walk(RECORDINGS);
  const lines = ["// Generated by scripts/gen-fixtures.ts from demo/recordings; do not edit.", ""];
  files.forEach((f, i) => lines.push(`import r${i} from "${relative(join(ROOT, "src", "worker", "generated"), f)}";`));
  lines.push("", `export const RECORDINGS: unknown[] = [${files.map((_, i) => `r${i}`).join(", ")}];`, "");
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const outputs: [string, string][] = [
    [OUT, render()],
    [OUT_REC, renderRecordings()],
  ];
  if (process.argv.includes("--check")) {
    for (const [path, next] of outputs) {
      let cur = "";
      try {
        cur = readFileSync(path, "utf8");
      } catch {
        cur = "";
      }
      if (cur !== next) {
        console.error(`${relative(ROOT, path)} is stale; run npm run fixtures:index`);
        process.exit(1);
      }
    }
    console.log("fixture and recording indexes are current");
  } else {
    for (const [path, next] of outputs) {
      writeFileSync(path, next);
      console.log(`wrote ${relative(ROOT, path)}`);
    }
  }
}
