// Small building blocks: status pills (icon + label, never color alone), chips, segmented controls, skeletons, empty
// and error states, and the "synthetic" label that appears wherever data is shown.
import type { ReactNode } from "react";
import { IconAlert, IconCheck, IconFlask, IconHold, IconInfo, IconStop } from "./icons";

export type Status = "good" | "warning" | "serious" | "critical" | "info" | "held";

const STATUS: Record<Status, { color: string; icon: (p: { size?: number }) => ReactNode }> = {
  good: { color: "var(--good)", icon: IconCheck },
  warning: { color: "var(--warning)", icon: IconAlert },
  serious: { color: "var(--serious)", icon: IconAlert },
  critical: { color: "var(--critical)", icon: IconStop },
  info: { color: "var(--muted)", icon: IconInfo },
  held: { color: "var(--warning)", icon: IconHold },
};

export function StatusPill({ status, children }: { status: Status; children: ReactNode }) {
  const s = STATUS[status];
  return (
    <span className="pill" data-status={status}>
      <span style={{ color: s.color, display: "inline-flex" }}>{s.icon({ size: 14 })}</span>
      {children}
    </span>
  );
}

export function Chip({ children, title }: { children: ReactNode; title?: string }) {
  return (
    <span className="chip" title={title}>
      {children}
    </span>
  );
}

export function SyntheticChip({ label = "Synthetic data" }: { label?: string }) {
  return (
    <Chip title="Larkspur Systems is a fictional company generated by a seeded program">
      <IconFlask size={12} />
      {label}
    </Chip>
  );
}

export function Segmented<T extends string | number>({ value, options, onChange, label }: { value: T; options: { value: T; label: string }[]; onChange: (v: T) => void; label: string }) {
  return (
    <div className="segmented" role="group" aria-label={label}>
      {options.map((o) => (
        <button key={String(o.value)} type="button" aria-pressed={o.value === value} onClick={() => onChange(o.value)}>
          {o.label}
        </button>
      ))}
    </div>
  );
}

export function Skeleton({ height = 160 }: { height?: number }) {
  return <div className="skeleton" style={{ height }} aria-busy="true" aria-label="Loading" />;
}

export function EmptyState({ children = "No data for this cohort; cohorts under 10 people are hidden." }: { children?: ReactNode }) {
  return <div className="empty">{children}</div>;
}

export function ErrorState({ error }: { error: Error }) {
  return (
    <div className="banner critical" role="alert">
      <IconStop size={16} />
      <div>
        <div className="banner-title">Could not load</div>
        <div className="banner-body">{error.message}</div>
      </div>
    </div>
  );
}

export function RefusalNote({ code, message }: { code: string; message: string }) {
  return (
    <div className="banner warning" role="note">
      <IconAlert size={16} />
      <div>
        <div className="banner-title">Not shown: {code}</div>
        <div className="banner-body">{message}</div>
      </div>
    </div>
  );
}
